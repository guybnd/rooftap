#!/usr/bin/env node
// Regenerates src/widgets/widget-glyphs.ts: the Lucide glyphs the home-screen
// widget draws in its leading tiles, as SVG path markup. The widget renders
// through react-native-android-widget, which can't mount lucide-react-native
// components, so it draws these through SvgWidget instead. Run after adding
// a name to ICONS:
//   node apps/mobile/scripts/gen-widget-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = [
  'alarm-clock',
  'calendar-clock',
  'calendar-days',
  'check',
  'folder-open',
  'layout-grid',
  'list-todo',
  'plus',
  'shopping-cart',
  'trash-2',
  'wallet',
];

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(dirname(require.resolve('lucide-react-native/package.json')), 'dist', 'esm', 'icons');

const escape = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');

const entries = ICONS.map((name) => {
  const source = readFileSync(join(iconsDir, `${name}.js`), 'utf8');
  const node = source.slice(source.indexOf('[', source.indexOf('createLucideIcon(')), source.lastIndexOf(']') + 1);
  // eslint-disable-next-line no-new-func
  const parsed = new Function(`return ${node}`)();
  const markup = parsed
    .map(([tag, attrs]) => {
      const props = Object.entries(attrs)
        .filter(([k]) => k !== 'key')
        .map(([k, v]) => `${k}="${escape(v)}"`)
        .join(' ');
      return `<${tag} ${props}/>`;
    })
    .join('');
  return `  '${name}': '${markup}',`;
});

const out = `// Generated by apps/mobile/scripts/gen-widget-glyphs.mjs from lucide-react-native. Do not edit.
export const WIDGET_GLYPHS = {
${entries.join('\n')}
} as const;

export type WidgetGlyph = keyof typeof WIDGET_GLYPHS;
`;
writeFileSync(join(here, '..', 'src', 'widgets', 'widget-glyphs.ts'), out);
console.log(`wrote ${ICONS.length} glyphs`);
