#!/usr/bin/env node
// Regenerates src/grocery-glyph-svgs.ts: one Fluent Emoji Flat SVG for every
// emoji the grocery matcher can return (grocery-icons.ts) plus the aisle icons
// (groceries.ts). Run after adding a keyword with a new emoji:
//   node packages/core/scripts/gen-grocery-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'src');

const icons = require('@iconify-json/fluent-emoji-flat/icons.json');
const chars = require('@iconify-json/fluent-emoji-flat/chars.json');

const EMOJI = /\p{Extended_Pictographic}️?/gu;
const strip = (e) => e.replace(/️/g, '');

const found = new Set();
for (const file of ['grocery-icons.ts', 'groceries.ts']) {
  for (const m of readFileSync(join(src, file), 'utf8').matchAll(EMOJI)) found.add(strip(m[0]));
}

const codepoints = (e) => [...e].map((c) => c.codePointAt(0).toString(16)).join('-');

const entries = [];
const missing = [];
for (const emoji of [...found].sort()) {
  const name = chars[codepoints(emoji)];
  const icon = name && (icons.icons[name] ?? icons.icons[icons.aliases?.[name]?.parent]);
  if (!icon) {
    missing.push(emoji);
    continue;
  }
  const w = icon.width ?? icons.width ?? 16;
  const h = icon.height ?? icons.height ?? 16;
  // Gradient ids are global on web: namespace them per glyph.
  const body = icon.body
    .replace(/id="([^"]+)"/g, `id="${name}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${name}-$1)`)
    .replace(/href="#([^"]+)"/g, `href="#${name}-$1"`);
  entries.push(`  ${JSON.stringify(emoji)}: ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${body}</svg>`)},`);
}

if (missing.length) {
  console.error(`No Fluent glyph for: ${missing.join(' ')}`);
  process.exit(1);
}

const out = `// GENERATED by scripts/gen-grocery-glyphs.mjs; do not edit by hand.
// Fluent Emoji Flat, (c) Microsoft Corporation, MIT licence:
// https://github.com/microsoft/fluentui-emoji/blob/main/LICENSE
// Keys are emoji with any U+FE0F variation selector removed.

export const GROCERY_GLYPH_SVGS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;
writeFileSync(join(src, 'grocery-glyph-svgs.ts'), out);
console.log(`Wrote ${entries.length} glyphs.`);
