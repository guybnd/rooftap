#!/usr/bin/env node
// Writes packages/core/src/database.types.ts: the Supabase `Database` type for
// the public schema, generated from a local database built from
// supabase/migrations. Run it after you add a migration:
//
//   npx supabase db start      (or `npx supabase db reset --local` if it is already running)
//   npm run db:types
//
// The header records the newest migration the file was built from, and
// apps/web/src/lib/database-types.test.ts fails while a newer migration
// exists, so the types can't silently fall behind the schema.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SUPABASE_CLI = "supabase@2.117.0";

const latest = readdirSync(path.join(root, "supabase/migrations"))
  .filter((f) => /^\d+_.*\.sql$/.test(f))
  .sort()
  .at(-1);
if (!latest) throw new Error("no migrations found");

const generated = execFileSync("npx", ["-y", SUPABASE_CLI, "gen", "types", "typescript", "--local", "--schema", "public"], {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
  shell: process.platform === "win32",
});

const header = `// Generated by scripts/db-types.mjs (npm run db:types). Do not edit by hand.
// Schema: public, from supabase/migrations up to ${latest.split("_")[0]}.
`;
writeFileSync(path.join(root, "packages/core/src/database.types.ts"), header + "\n" + generated);
console.log(`database.types.ts written from migrations up to ${latest}`);
